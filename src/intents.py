# Priority ordering for disambiguation when multiple intents match:
# 1. Damage & Defect is most urgent and specific.
# 2. Cancellation is highly time-sensitive.
# 3. Return & Refund takes priority over generic delivery/billing.
# 4. Payment & Billing precedes delivery.
# 5. Account Security is critical.
# 6. Delivery Tracking is high volume and operational.
# 7. Prime & Digital Services.
# 8. Product & Seller inquiries.
# 9. Generic Feedback / Chatter.
PRIORITY_ORDER: List[str] = [
    "damaged_defective_wrong_item",
    "order_cancellation_modification",
    "return_refund_exchange",
    "payment_billing_promotions",
    "account_access_security",
    "delivery_status_tracking",
    "prime_digital_services",
    "product_seller_inquiry",
    "feedback_complaint_chatter",
]


def classify_message_intent(text: str) -> Tuple[str, float, str]:
    """
    Classify a customer message using deterministic priority regex rules.
    Returns: (intent_name, confidence, labeling_method)

    - Confidence is 0.85 for unambiguous single/priority rule matches.
    - Confidence is 0.30 for unmatched fallback ('other_unclear').
    """
    for intent in PRIORITY_ORDER:
        pat = INTENT_PATTERNS[intent]
        if pat.search(text):
            return intent, 0.85, f"regex_rule_{intent}"

    return "other_unclear", 0.30, "fallback_unmatched"


