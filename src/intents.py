def build_dev_record(
    conversation: Dict[str, Any],
    interaction_pair: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Construct a single labeled development dataset example from an interaction pair.
    Preserves conversational context for future context-ablation experiments.
    """
    cust_text = interaction_pair["customer_text"]
    cleaned = clean_tweet_text(cust_text)
    intent, conf, method = classify_message_intent(cust_text)

    return {
        "conversation_id": conversation["conversation_id"],
        "root_id": conversation["root_id"],
        "turn_index": interaction_pair["turn_index"],
        "customer_tweet_id": interaction_pair["customer_tweet_id"],
        "customer_author_id": interaction_pair["customer_author_id"],
        "customer_message": cust_text,
        "cleaned_text": cleaned,
        "support_tweet_id": interaction_pair["support_tweet_id"],
        "support_response": interaction_pair["support_text"],
        "prior_context": interaction_pair.get("prior_context", []),
        "intent": intent,
        "confidence": conf,
        "labeling_method": method,
    }


def extract_dev_dataset_from_conversations(
    conversations: List[Dict[str, Any]],
    turn1_only: bool = False,
) -> List[Dict[str, Any]]:
    """
    Extract development examples from a list of conversation objects.
    If turn1_only is True, extracts only the opening customer inquiry (turn_index == 1).
    Otherwise extracts all direct interaction pairs while recording turn_index.
    """
    records = []
    for conv in conversations:
        for pair in conv.get("interaction_pairs", []):
            if turn1_only and pair["turn_index"] != 1:
                continue
            record = build_dev_record(conv, pair)
            records.append(record)
    return records
