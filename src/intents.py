def clean_tweet_text(text: str) -> str:
    """
    Standard NLP cleaner for Twitter support text.
    Removes handles (@username, @12345) and URLs to prevent overfitting to specific IDs,
    while preserving actual natural language tokens, punctuation, and casing.
    """
    # Remove URLs
    text = re.sub(r"https?://\S+", " ", text)
    # Remove user mentions
    text = re.sub(r"@\w+", " ", text)
    # Collapse multiple whitespace
    text = re.sub(r"\s+", " ", text).strip()
    return text


