"""
Intent taxonomy, development labeling rules, text normalization, and dataset extraction
for AmazonHelp customer support conversations.

NOTE ON LABELING METHODOLOGY:
Labels generated by this module are deterministic, rule-based WEAK/DEVELOPMENT LABELS
designed strictly to establish baseline feasibility, debug modeling pipelines, and
perform error analysis prior to human annotation. They MUST NOT be confused with or
reported as human gold-standard ground truth.

PRODUCTION CLASSIFIER (Candidate D — Hybrid):
The ``HybridIntentClassifier`` class implements the production-selected Candidate D
architecture: a high-precision deterministic regex cascade (confidence ≥ 0.85) that
triage unambiguous intents, backed by a Balanced LinearSVC trained on Word+Char TF-IDF
features (50k-feature FeatureUnion) for the remaining cases.  It is evaluated once on
the frozen 200-example Human Golden Set: 57.00% accuracy / 0.5971 Macro-F1, an
absolute +18.50 pp / +0.1937 Macro-F1 improvement over the TF-IDF+LR baseline.
"""

