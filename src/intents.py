# Production Classifier: Candidate D — Hybrid (Regex Cascade + ML Fallback)
# ------------------------------------------------------------------------------

_DEFAULT_TRAIN_FILE = (
    Path(__file__).resolve().parent.parent
    / "data/processed/amazonhelp_dev_train.jsonl"
)


class HybridIntentClassifier:
    """
    Production intent classifier — Candidate D (selected by Validation Macro-F1).

    Architecture
    ------------
    1. **Regex cascade** (confidence ≥ 0.85): deterministic, zero-latency triage for
       the 9 operational intents using ``classify_message_intent``.
    2. **ML fallback**: Balanced ``LinearSVC`` (C=0.5, dual=False) trained on a
       50,000-feature ``FeatureUnion`` of Word TF-IDF n-grams (1-2) and character
       subword n-grams (3-5) for examples not captured with high confidence by the
       regex stage.

    Training Data
    -------------
    Strictly ``data/processed/amazonhelp_dev_train.jsonl`` (57,760 weak-label
    examples).  The 200-example frozen Human Golden Set is *never* used for training.

    Performance on Frozen 200-Example Human Golden Set
    --------------------------------------------------
    * Accuracy:   57.00%   (+18.50 pp vs. TF-IDF+LR baseline of 38.50%)
    * Macro-F1:    0.5971  (+0.1937 vs. baseline of 0.4034)
    * Weighted-F1: 0.5915

    Usage
    -----
    >>> clf = HybridIntentClassifier()   # trains lazily on first call or at init
    >>> intent, conf, method = clf.classify("Where is my order?")
    """

    def __init__(
        self,
        train_file: Optional[Path] = None,
        regex_confidence_threshold: float = 0.85,
    ) -> None:
        self._train_file = Path(train_file) if train_file else _DEFAULT_TRAIN_FILE
        self._threshold = regex_confidence_threshold
        self._vectorizer = None  # FeatureUnion, fitted lazily
        self._clf = None         # LinearSVC, fitted lazily
        self._is_trained = False

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def classify(self, text: str) -> Tuple[str, float, str]:
        """
        Classify a customer message using the Candidate D hybrid architecture.

        Parameters
        ----------
        text:
            Raw customer tweet text (handles and URLs will be stripped internally).

        Returns
        -------
        (intent_name, confidence, method)
            * ``intent_name`` — one of the 10 canonical intent labels.
            * ``confidence``  — 0.85 for regex hits, 0.75 for ML predictions,
              0.30 for unmatched fallback.
            * ``method``      — provenance tag: ``"regex_rule_<intent>"``,
              ``"hybrid_ml_svc"``, or ``"hybrid_fallback_unmatched"``.
        """
        # Stage 1: high-precision regex cascade
        rule_intent, rule_conf, rule_method = classify_message_intent(text)
        if rule_conf >= self._threshold and rule_intent != "other_unclear":
            return rule_intent, rule_conf, rule_method

        # Stage 2: ML fallback — train on demand if needed
        if not self._is_trained:
            self._train()

        if self._clf is None:
            # Training data unavailable — degrade gracefully to regex result
            return rule_intent, rule_conf, rule_method

        cleaned = clean_tweet_text(text)
        X = self._vectorizer.transform([cleaned])
        pred = self._clf.predict(X)[0]

        if pred == "other_unclear":
            return pred, 0.30, "hybrid_fallback_unmatched"
        return pred, 0.75, "hybrid_ml_svc"

    @property
    def is_trained(self) -> bool:
        """True if the ML fallback model has been fitted."""
        return self._is_trained

    def train(self, train_file: Optional[Path] = None) -> "HybridIntentClassifier":
        """Explicitly train the ML fallback.  Returns self for chaining."""
        self._train(train_file=train_file)
        return self

    # ------------------------------------------------------------------
    # Internal
    # ------------------------------------------------------------------

    def _train(self, train_file: Optional[Path] = None) -> None:
        """Fit the Word+Char FeatureUnion and LinearSVC on the dev-train file."""
        path = Path(train_file) if train_file else self._train_file
        if not path.exists():
            # Graceful degradation: mark as trained (no-op ML stage)
            self._is_trained = True
            return

        try:
            from sklearn.feature_extraction.text import TfidfVectorizer
            from sklearn.pipeline import FeatureUnion
            from sklearn.svm import LinearSVC
        except ImportError as exc:  # pragma: no cover
            raise ImportError(
                "scikit-learn is required for HybridIntentClassifier. "
                "Install it with: pip install scikit-learn"
            ) from exc

        records: List[Dict[str, Any]] = []
        with open(path, "r", encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line:
                    records.append(json.loads(line))

        train_texts = [r.get("cleaned_text") or clean_tweet_text(r.get("customer_message", "")) for r in records]
        train_labels = [r["intent"] for r in records]

        vectorizer = FeatureUnion([
            ("word", TfidfVectorizer(
                ngram_range=(1, 2), min_df=2, max_features=25000, sublinear_tf=True
            )),
            ("char", TfidfVectorizer(
                ngram_range=(3, 5), analyzer="char_wb", min_df=5,
                max_features=25000, sublinear_tf=True,
            )),
        ])
        X_train = vectorizer.fit_transform(train_texts)

        clf = LinearSVC(C=0.5, class_weight="balanced", dual=False, random_state=42, max_iter=2000)
        clf.fit(X_train, train_labels)

        self._vectorizer = vectorizer
        self._clf = clf
        self._is_trained = True


