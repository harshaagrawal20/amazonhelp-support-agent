def normalize_intent_label(label: str) -> str:
    """Normalize any alias or legacy label into the canonical taxonomy name."""
    clean = label.strip().lower()
    if clean in INTENT_TAXONOMY:
        return clean
    if clean in LABEL_ALIASES:
        return LABEL_ALIASES[clean]
    raise ValueError(f"Unknown intent label '{label}'. Must be one of: {INTENT_NAMES}")


